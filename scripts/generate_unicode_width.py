#!/usr/bin/env python3
"""Generate pure Lean display-width intervals from the active C.UTF-8 libc.

Run in `nix develop .#llvm` when updating the pinned toolchain/Unicode data.
GNU expand uses the same locale's wcwidth behavior for non-ASCII scalars.
"""
import ctypes
import locale
from pathlib import Path

locale.setlocale(locale.LC_CTYPE, "C.UTF-8")
libc = ctypes.CDLL(None)
libc.wcwidth.argtypes = [ctypes.c_wchar]
libc.wcwidth.restype = ctypes.c_int


def intervals(width: int) -> list[tuple[int, int]]:
    spans = []
    start = None
    for scalar in range(0x80, 0x110000):
        matches = libc.wcwidth(chr(scalar)) == width
        if matches and start is None:
            start = scalar
        elif not matches and start is not None:
            spans.append((start, scalar - 1))
            start = None
    if start is not None:
        spans.append((start, 0x10FFFF))
    return spans


def lean_array(spans: list[tuple[int, int]]) -> str:
    rows = [f"  ({start}, {stop})" for start, stop in spans]
    return "#[\n" + ",\n".join(rows) + "\n]"


zero = lean_array(intervals(0))
double = lean_array(intervals(2))
source = f'''/- Generated by scripts/generate_unicode_width.py from C.UTF-8 wcwidth.
   This is data, kept in Lean so the expand transducer remains pure. -/
import Lutils.Shared.Common

namespace Lutils

private def zeroWidthRanges : Array (Nat × Nat) := {zero}

private def doubleWidthRanges : Array (Nat × Nat) := {double}

/-- Membership in a sorted, disjoint table of inclusive scalar intervals. -/
private def unicodeWidthContains (ranges : Array (Nat × Nat)) (scalar : Nat) : Bool := Id.run do
  let mut low := 0
  let mut high := ranges.size
  while low < high do
    let middle := low + (high - low) / 2
    match ranges[middle]? with
    | none => return false
    | some (first, last) =>
        if scalar < first then high := middle
        else if scalar > last then low := middle + 1
        else return true
  return false

/-- Display cells occupied by one valid non-ASCII scalar in C.UTF-8. -/
def unicodeScalarCells (scalar : Nat) : Nat :=
  if unicodeWidthContains zeroWidthRanges scalar then 0
  else if unicodeWidthContains doubleWidthRanges scalar then 2
  else 1

theorem unicodeScalarCells_le_two (scalar : Nat) :
    unicodeScalarCells scalar ≤ 2 := by
  cases hzero : unicodeWidthContains zeroWidthRanges scalar <;>
    cases hdouble : unicodeWidthContains doubleWidthRanges scalar <;>
    simp [unicodeScalarCells, hzero, hdouble]

end Lutils
'''
Path("Lutils/Shared/UnicodeWidth.lean").write_text(source)
